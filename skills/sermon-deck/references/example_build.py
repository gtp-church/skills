"""Образец сборки конкретной проповеди.

Скопируй рядом с конспектом, замени содержимое, запусти. Показаны все типы
слайдов и то, как раскладывать конспект по комментариям докладчика.

    uv run example_build.py --skill-dir /путь/к/sermon-deck --output Проповедь.pptx
"""
import argparse
import sys
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--skill-dir', type=Path, default=Path(__file__).resolve().parents[1],
                    help='Путь к sermon-deck, если пример скопирован в другую папку')
parser.add_argument('--output', type=Path, default=Path('Проповедь.pptx'))
args = parser.parse_args()
SCRIPTS = str(args.skill_dir.resolve() / 'scripts')
OUT = str(args.output.resolve())

sys.path.insert(0, SCRIPTS)
from deckbuilder import Deck, newest_template

# Фрагменты конспекта — дословно, в порядке чтения. Отдельным словарём, чтобы
# в конце проверить, что каждый попал в заметки ровно один раз.
K = {
    'p1': 'Искупление — кардинальное вероучение. Если мы ошибаемся в нем, тогда, как мне '
          'кажется, не имеет особого значения, что мы думаем по другим вопросам веры.',
    'h1': 'ПРИРОДА БОГА — СВЯТОСТЬ',
    'p2': 'Это совершенная и полная святость… в этом сама Его сущность. Грех, будучи '
          'противным Божьей природе, несовместим с Ним.',
    'p3': 'Не надо забывать и о том, что нарушение закона ведет к серьезным последствиям — '
          'наказанию и, в частности, смерти.',
    'p4': 'Павел писал, что «возмездие за грех — смерть» (Рим. 6:23).',
    'p5': 'Благодарность Богу за: Агнца. Христос занял наше место под Божьим судом.',
    'p6': 'Умилостивление. Смерть Христа удовлетворила Божью справедливость.',
}

d = Deck()   # вшитый шаблон
# Если рядом есть папка с готовыми презентациями — стиль лучше брать из неё:
# d = Deck(newest_template('/путь/к/Референсные презентации'))

# Титул: название жёлтым, подзаголовок белым, ниже — ключевой текст проповеди.
d.title([('ИСКУПЛЕНИЕ', 150, 'yellow'),
         ('В ЧЕМ СМЫСЛ И ЗНАЧЕНИЕ?', 72, 'white'),
         ('От Матфея 20:28', 48, 'white')],
        notes='В чем смысл и значение Искупления? — 06.09.2026.\n'
              'Ключевой текст проповеди: От Матфея 20:28.')

# Крупная мысль; часть строки — жёлтым.
d.statement('ИСКУПЛЕНИЕ – КАРДИНАЛЬНОЕ ВЕРОУЧЕНИЕ', accent='КАРДИНАЛЬНОЕ', notes=K['p1'])

# Стих: текст из конспекта дословно, если он там процитирован.
d.verse('Матфея 20:28',
        'Подобно тому как Сын Человеческий пришёл не для того, чтобы Ему служили, '
        'но чтобы Самому служить и отдать Свою жизнь как выкуп за спасение многих жизней',
        notes='Ключевой текст проповеди (перевод из конспекта).')

# Раздел: разделитель, затем список. Пункты — короткие опоры для устной речи.
d.divider('I', 'ПРИРОДА БОГА – СВЯТОСТЬ', notes=f'Раздел I. {K["h1"]}')
d.bullets('Природа Бога – святость',
          ['Святость – сущность Бога',
           'Грех несовместим с Богом',
           'Бог не может терпеть грех'],
          notes=K['p2'])

d.divider('II', 'ГРЕХ ВЕДЕТ К СМЕРТИ', notes='Раздел II. ГРЕХ ВЕДЕТ К СМЕРТИ')
d.bullets('Грех ведет к смерти',
          ['Нарушение закона – наказание',
           'Возмездие за грех – смерть',
           'Связь греха и смерти прямая'],
          notes=K['p3'])

# Стих, которого нет в конспекте дословно, — синодальный текст, сверенный по azbyka.ru.
d.verse('Римлянам 6:23',
        'Ибо возмездие за грех – смерть, а дар Божий – жизнь вечная '
        'во Христе Иисусе, Господе нашем',
        notes=K['p4'])

# Плашка-предупреждение.
d.callout('Важно!',
          'Мы не оправдываемся на основании освящения, но оправдания не бывает '
          'без начала освящения',
          notes='Важно! Мы не оправдываемся на основании нашего освящения…')

# Один содержательный итоговый список; дополнительный экран «ВЫВОД» не нужен.
CONCLUSION = ['Агнца – Он занял наше место', 'Умилостивление Божьего гнева']
d.bullets('Благодарность Богу', CONCLUSION,
          notes=K['p5'] + '\n\n' + K['p6'], size=54)

d.poem(['Спаситель! Так может ли быть,',
        'Что кровь Ты пролил за меня,'],
       'Чарльз Уэсли, 1738',
       notes='Спаситель! Так может ли быть, / Что кровь Ты пролил за меня…')

d.save(OUT, title='В чем смысл и значение Искупления?')

# Контроль: весь ли конспект попал в заметки и нет ли дублей.
from pptx import Presentation
notes = '\n'.join(s.notes_slide.notes_text_frame.text for s in Presentation(OUT).slides)
missing = [k for k, v in K.items() if v.strip() not in notes]
dups = [k for k, v in K.items() if notes.count(v.strip()) > 1]
print('не попало в заметки:', missing or 'ничего')
print('продублировано:', dups or 'ничего')

if missing or dups:
    raise SystemExit('Ошибка покрытия заметок докладчика')
